// gen-tex-tables.js — regenerate src/core/tex-tables.js from the public-domain
// https://github.com/ypsu/latex-to-unicode data files. One-off/dev-only: the
// generated module is committed, so builds never depend on the sibling repo.
//
//   node tools/gen-tex-tables.js [path-to-latex-to-unicode-checkout]
//
// Only the *data* is harvested. That repo's conversion algorithm (global
// string replaces) is deliberately not ported — the tokenizer lives in
// src/core/tex-unicode.js.
"use strict";

const fs = require("fs");
const path = require("path");

const srcRepo = process.argv[2] || path.join(__dirname, "..", "..", "latex-to-unicode");
const outFile = path.join(__dirname, "..", "src", "core", "tex-tables.js");

// "key value" per line -> { key: value }, keys sorted for stable diffs.
function loadPairs(file) {
  const map = {};
  const lines = fs.readFileSync(path.join(srcRepo, "data", file), "utf8").split("\n");
  for (const line of lines) {
    const words = line.split(/\s+/).filter(Boolean);
    if (words.length >= 2) map[words[0]] = words[1];
  }
  const sorted = {};
  for (const k of Object.keys(map).sort()) sorted[k] = map[k];
  return sorted;
}

const tables = {
  symbols: loadPairs("symbols"),
  alphabets: {
    cal: loadPairs("textcal"),
    bb: loadPairs("textbb"),
    frak: loadPairs("textfrak"),
  },
};

const counts =
  Object.keys(tables.symbols).length +
  " symbols; alphabets: cal " +
  Object.keys(tables.alphabets.cal).length +
  ", bb " +
  Object.keys(tables.alphabets.bb).length +
  ", frak " +
  Object.keys(tables.alphabets.frak).length;

const body = JSON.stringify(tables, null, 2).replace(/\n/g, "\n");

const out = `// tex-tables.js — GENERATED by tools/gen-tex-tables.js; do not edit by hand.
// LaTeX -> Unicode lookup tables harvested from the public-domain
// https://github.com/ypsu/latex-to-unicode (data/{symbols,textcal,textbb,textfrak}).
// ${counts}.
// Structural commands (\\frac, \\text, \\left, _{}/^{}) are grammar, not table
// entries — they live in core/tex-unicode.js.
var GA = (typeof GA !== "undefined" && GA) || {};
GA.core = GA.core || {};

GA.core.texTables = ${body};

if (typeof module !== "undefined" && module.exports) module.exports = GA.core.texTables;
`;

fs.writeFileSync(outFile, out);
console.log("wrote " + outFile + " (" + counts + ")");
